# ── Model Concordance ─────────────────────────────────────────────────────
def make_concordance():
    src = REPORTS_DIR / "concordance_audit.json"
    require(src)
    with open(src) as f:
        data = json.load(f)
    print(r"""\begin{table}[t]
\centering
\caption{Inter-model decision concordance (Cohen's $\kappa$ and raw agreement $P_o$) across normative credit strata. Under unanimous agreement on single-class strata, Cohen's $\kappa$ is mathematically undefined ($0/0$) and reported as NaN rather than 1.0.}
\label{tab:app_concordance}
\vspace{2pt}
\scriptsize
\setlength{\tabcolsep}{3.5pt}
\begin{tabular}{@{}lcc@{}}
\toprule
\textbf{Stratum} & \textbf{Cohen's $\kappa$} & \textbf{Raw Agreement $P_o$} \\
\midrule""")
    strata = data.get("strata", {})
    for stratum, vals in strata.items():
        kappa = vals.get("kappa", "NaN")
        po    = vals.get("po", "N/A")
        kappa_str = f"{kappa:.3f}" if isinstance(kappa, float) else "NaN"
        po_str    = f"{po:.3f}"    if isinstance(po,    float) else str(po)
        print(f"{stratum} & ${kappa_str}$ & ${po_str}$ \\\\")
    print(r"""\bottomrule
\end{tabular}
\end{table}
""")


